"""
LOB Encoder: High-Frequency Limit Order Book Extraction & Neural Representation
==============================================================================
Synthesizes cutting-edge empirical finance and machine learning methodologies:
  - Gould et al. (2013): Order Flow Imbalance (OFI), liquidity resilience, queue dynamics.
  - DeepLOB (Zhang et al., 2020): Spatial convolution over price depths and volumes.
  - Rahimikia & Poon (2026): XAI core volatility predictors (Mid price, Mean Bid/Ask depth, Imbalance).
  - LOBDIF (Zheng et al., 2026): Event stream density, type interdependency, and message velocity.

This module transforms continuous LOB tick updates and JSON book snapshots across any arbitrary
temporal window [t_start, t_end] into a rich empirical feature matrix and a dense trainable
PyTorch node embedding ready to aid Heterogeneous Graph market node representations.
"""

import json
import logging
from typing import List, Optional, Dict, Any, Tuple
import numpy as np
import pandas as pd
import torch
import torch.nn as nn
import torch.nn.functional as F

logger = logging.getLogger(__name__)

# Default empirical feature names generated by LOBFeatureExtractor
LOB_FEATURE_NAMES = [
    "mid_price",
    "spread",
    "best_bid",
    "best_ask",
    "ofi",                  # Order Flow Imbalance (Gould et al.)
    "total_event_volume",   # Cumulative volume delta in window
    "event_count",          # LOB message velocity (LOBDIF)
    "buy_event_ratio",      # Proportion of buy side tick modifications
    "cancel_velocity",      # Proportion of reducing volume ticks (cancellations/depletions)
    "mean_bid_depth",       # Mean standing bid volume in near-book (Rahimikia & Poon XAI)
    "mean_ask_depth",       # Mean standing ask volume in near-book (Rahimikia & Poon XAI)
    "depth_skewness",       # (Bid Depth - Ask Depth) / (Bid Depth + Ask Depth)
]


class LOBFeatureExtractor:
    """
    Extracts empirical microstructure alpha features and LOB depth silhouettes across
    an arbitrary time interval [t_start, t_end] for a target set of markets.
    
    Fuses periodic JSON book snapshots with continuous real-time orderbook tick updates
    to prevent Last-Observation-Carried-Forward (LOCF) blind spots and capture Order Flow Imbalance.
    """
    def __init__(self, depth_levels: int = 5, depth_price_band: float = 0.05):
        """
        Args:
            depth_levels: Number of price depth levels to consider for spatial representations.
            depth_price_band: Price window (e.g. 0.05 = 5 cents) from mid-price to compute standing depths.
        """
        self.depth_levels = depth_levels
        self.depth_price_band = depth_price_band

    def extract(
        self,
        market_ids: List[str],
        orderbook_df: pd.DataFrame,
        snapshots_df: pd.DataFrame,
        t_start: Optional[pd.Timestamp | str] = None,
        t_end: Optional[pd.Timestamp | str] = None,
    ) -> pd.DataFrame:
        """
        Extract a feature DataFrame indexed by market_id containing the 12 core empirical metrics
        for the exact time interval [t_start, t_end].
        """
        # Initialize default features matrix (zeros / defaults)
        df_feats = pd.DataFrame(index=market_ids, columns=LOB_FEATURE_NAMES, dtype=np.float32)
        df_feats.fillna(0.0, inplace=True)
        # Default pricing defaults for uninitialized markets
        df_feats["mid_price"] = 0.50
        df_feats["best_bid"] = 0.49
        df_feats["best_ask"] = 0.51
        df_feats["spread"] = 0.02

        if orderbook_df is None or len(market_ids) == 0:
            return df_feats

        # Filter orderbook events to window if start/end provided
        ob_win = orderbook_df
        if t_start is not None or t_end is not None:
            ts_col = ob_win["timestamp_received"]
            if t_start is not None:
                ob_win = ob_win[ts_col >= pd.to_datetime(t_start)]
            if t_end is not None:
                ob_win = ob_win[ts_col <= pd.to_datetime(t_end)]

        # Filter only relevant markets
        ob_win = ob_win[ob_win["market_id"].isin(market_ids)]

        if not ob_win.empty:
            # ─────────────────────────────────────────────────────────────
            # 1. Price States (Latest observation at or prior to t_end)
            # ─────────────────────────────────────────────────────────────
            latest_idx = ob_win.groupby("market_id", observed=True)["timestamp_received"].idxmax()
            latest_rows = ob_win.loc[latest_idx].set_index("market_id")
            
            for col in ["mid_price", "best_bid", "best_ask", "spread"]:
                if col in latest_rows.columns:
                    # Fill available latest observations
                    valid = latest_rows[col].notnull()
                    df_feats.loc[valid.index[valid], col] = latest_rows.loc[valid, col].astype(np.float32)

            # ─────────────────────────────────────────────────────────────
            # 2. Order Flow Imbalance (OFI) & Message Velocity (Gould & LOBDIF)
            # ─────────────────────────────────────────────────────────────
            # Convert change_side to numeric direction (+1 for BUY/bid update, -1 for SELL/ask update)
            ob_copy = ob_win[["market_id", "change_side", "change_size", "change_price"]].copy()
            ob_copy["is_buy"] = (ob_copy["change_side"].str.upper() == "BUY").astype(np.float32)
            ob_copy["sign"] = np.where(ob_copy["is_buy"] == 1.0, 1.0, -1.0)
            ob_copy["size_clean"] = ob_copy["change_size"].fillna(0.0).astype(np.float32)
            
            # Signed volume contribution for OFI
            ob_copy["ofi_contrib"] = ob_copy["sign"] * ob_copy["size_clean"]
            # Detect volume drop (cancellations / liquidity depletions)
            ob_copy["is_cancel"] = (ob_copy["size_clean"] < 0).astype(np.float32)
            ob_copy["abs_size"] = np.abs(ob_copy["size_clean"])

            agg_stats = ob_copy.groupby("market_id", observed=True).agg(
                ofi=("ofi_contrib", "sum"),
                total_vol=("abs_size", "sum"),
                count=("abs_size", "count"),
                buy_count=("is_buy", "sum"),
                cancel_count=("is_cancel", "sum")
            )

            idx_overlap = agg_stats.index.intersection(df_feats.index)
            df_feats.loc[idx_overlap, "ofi"] = agg_stats.loc[idx_overlap, "ofi"].astype(np.float32)
            df_feats.loc[idx_overlap, "total_event_volume"] = agg_stats.loc[idx_overlap, "total_vol"].astype(np.float32)
            df_feats.loc[idx_overlap, "event_count"] = agg_stats.loc[idx_overlap, "count"].astype(np.float32)
            
            counts = agg_stats.loc[idx_overlap, "count"] + 1e-5
            df_feats.loc[idx_overlap, "buy_event_ratio"] = (agg_stats.loc[idx_overlap, "buy_count"] / counts).astype(np.float32)
            df_feats.loc[idx_overlap, "cancel_velocity"] = (agg_stats.loc[idx_overlap, "cancel_count"] / counts).astype(np.float32)

        # ─────────────────────────────────────────────────────────────
        # 3. Snapshot LOB Near-Book Depth Extraction (Rahimikia & Poon)
        # ─────────────────────────────────────────────────────────────
        if snapshots_df is not None and not snapshots_df.empty:
            snap_win = snapshots_df[snapshots_df["market_id"].isin(market_ids)]
            if t_end is not None:
                snap_win = snap_win[snap_win["timestamp_received"] <= pd.to_datetime(t_end)]

            if not snap_win.empty:
                latest_snaps = snap_win.sort_values("timestamp_received").groupby("market_id", observed=True).tail(1)
                for _, row in latest_snaps.iterrows():
                    m_id = row["market_id"]
                    if m_id not in df_feats.index:
                        continue
                    raw_json = row.get("data")
                    if not raw_json:
                        continue
                    try:
                        parsed = json.loads(raw_json) if isinstance(raw_json, str) else raw_json
                        bids = parsed.get("bids", [])
                        asks = parsed.get("asks", [])
                        mid = df_feats.loc[m_id, "mid_price"]
                        
                        # Calculate standing volume within price band of mid-price
                        bid_vols = [float(item[1]) for item in bids if (mid - float(item[0])) <= self.depth_price_band]
                        ask_vols = [float(item[1]) for item in asks if (float(item[0]) - mid) <= self.depth_price_band]
                        
                        mean_b = np.mean(bid_vols) if len(bid_vols) > 0 else 0.0
                        mean_a = np.mean(ask_vols) if len(ask_vols) > 0 else 0.0
                        
                        df_feats.loc[m_id, "mean_bid_depth"] = float(mean_b)
                        df_feats.loc[m_id, "mean_ask_depth"] = float(mean_a)
                        
                        denom = mean_b + mean_a + 1e-5
                        df_feats.loc[m_id, "depth_skewness"] = float((mean_b - mean_a) / denom)
                    except Exception:
                        pass # Retain zero default if malformed JSON

        return df_feats

    def extract_tensor(
        self,
        market_ids: List[str],
        orderbook_df: pd.DataFrame,
        snapshots_df: pd.DataFrame,
        t_start: Optional[pd.Timestamp | str] = None,
        t_end: Optional[pd.Timestamp | str] = None,
    ) -> torch.Tensor:
        """Returns empirical feature matrix as a PyTorch FloatTensor of shape [N_markets, 12]."""
        df = self.extract(market_ids, orderbook_df, snapshots_df, t_start, t_end)
        return torch.tensor(df.values, dtype=torch.float32)


# ─────────────────────────────────────────────────────────────────────────────
# Neural LOB Representation Architecture (DeepLOB + LOBDIF Inspired)
# ─────────────────────────────────────────────────────────────────────────────

class DeepLOBMicroBlock(nn.Module):
    """
    Lightweight spatial Convolution / ResNet block inspired by DeepLOB (Zhang et al.).
    Applies dense temporal-spatial projections over orderbook feature dynamics.
    """
    def __init__(self, in_features: int, hidden_dim: int):
        super().__init__()
        self.fc1 = nn.Linear(in_features, hidden_dim)
        self.ln1 = nn.LayerNorm(hidden_dim)
        self.conv_spatial = nn.Conv1d(in_channels=1, out_channels=4, kernel_size=3, padding=1)
        self.fc2 = nn.Linear(hidden_dim * 4, hidden_dim)
        self.ln2 = nn.LayerNorm(hidden_dim)
        self.act = nn.SiLU()  # Modern smooth ReLU alternative

    def forward(self, x: torch.Tensor) -> torch.Tensor:
        # x shape: [Batch, in_features]
        h = self.act(self.ln1(self.fc1(x)))
        # Expand to channel dimension for spatial feature convolution [Batch, 1, hidden_dim]
        h_conv = h.unsqueeze(1)
        out_conv = self.act(self.conv_spatial(h_conv))  # Shape: [Batch, 4, hidden_dim]
        # Flatten spatial feature maps
        out_flat = out_conv.view(x.size(0), -1)
        out_dense = self.act(self.ln2(self.fc2(out_flat)))
        # Residual connection if dimensions match
        if h.shape == out_dense.shape:
            return h + out_dense
        return out_dense


class LOBNeuralEncoder(nn.Module):
    """
    Unified LOB Neural Representation Module.
    Takes the raw empirical 12-dimensional LOB microstructure metrics (OFI, depth skew, 
    cancellation velocity, mean depth) and projects them into a dense, invariant latent embedding
    z_LOB of size `out_dim` (default 32 or 64).

    This dense embedding z_LOB is concatenated or integrated into the market node embedding
    before Graph Neural Network (GNN) message passing across wallet transaction edges.
    """
    def __init__(
        self,
        in_dim: int = 12,
        hidden_dim: int = 64,
        out_dim: int = 32,
        dropout: float = 0.15,
    ):
        super().__init__()
        self.in_dim = in_dim
        self.out_dim = out_dim

        # Input projection and feature normalization
        self.input_norm = nn.BatchNorm1d(in_dim)
        
        # DeepLOB inspired micro-spatial extraction block
        self.spatial_block = DeepLOBMicroBlock(in_dim, hidden_dim)
        
        # LOBDIF style event-interdependency gating network (Gated Residual)
        self.gate = nn.Sequential(
            nn.Linear(hidden_dim, hidden_dim),
            nn.Sigmoid()
        )
        
        # Final embedding projection
        self.out_proj = nn.Sequential(
            nn.Dropout(dropout),
            nn.Linear(hidden_dim, out_dim),
            nn.LayerNorm(out_dim),
            nn.SiLU()
        )

    def forward(self, lob_features: torch.Tensor) -> torch.Tensor:
        """
        Args:
            lob_features: Tensor of shape [N_markets, 12] containing empirical LOB attributes.
        Returns:
            z_LOB: Dense latent LOB embedding of shape [N_markets, out_dim] ready for GNN fusion.
        """
        # Handle single node case for BatchNorm
        if lob_features.size(0) > 1:
            x = self.input_norm(lob_features)
        else:
            x = lob_features

        # Spatial feature convolution
        h = self.spatial_block(x)
        
        # Event interdependency attention gating
        gated_h = h * self.gate(h)
        
        # Project to dense representation
        z_lob = self.out_proj(gated_h)
        return z_lob


# ─────────────────────────────────────────────────────────────────────────────
# Spatiotemporal Replay (Event-Clock: 1 Snapshot + N Ticks + Time Intensity)
# ─────────────────────────────────────────────────────────────────────────────

class SpatiotemporalLOBExtractor:
    """
    Implements Volume-Clock / Event-Driven LOB reconstruction.
    For each target market, locates an anchor book snapshot and replays up to `seq_len`
    subsequent orderbook tick updates (`change_price`, `change_size`, `change_side`).

    Crucially incorporates Explicit Temporal Intensity: because 20 updates inside 2 seconds
    represent high-frequency institutional execution urgency whereas 20 updates across 17 minutes
    represent ambient retail noise, every temporal slice is enriched with explicit time delta
    (elapsed seconds since snapshot) and instantaneous message velocity (Hz).
    """
    def __init__(self, seq_len: int = 20, depth_levels: int = 10):
        """
        Args:
            seq_len: Number of tick updates after the anchor snapshot to replay (default 20).
            depth_levels: Top L bid and ask price levels to retain in spatial ladder (default 10).
        """
        self.seq_len = seq_len
        self.depth_levels = depth_levels

    def extract_tensor(
        self,
        market_ids: List[str],
        orderbook_df: pd.DataFrame,
        snapshots_df: pd.DataFrame,
        t_end: Optional[pd.Timestamp | str] = None,
    ) -> Tuple[torch.Tensor, torch.Tensor]:
        """
        Reconstructs the spatiotemporal depth evolutionary trajectory.

        Returns:
            spatial_tensor: FloatTensor of shape [N_markets, channels=5, seq_len, depth_levels]
                            Channels are: [Bid_Dist_to_Mid, Bid_Vol, Ask_Dist_to_Mid, Ask_Vol, Log_Elapsed_Sec]
            mask_tensor:    BooleanTensor of shape [N_markets] indicating which markets successfully
                            had >= 1 snapshot and >= 1 subsequent tick event to reconstruct.
        """
        N = len(market_ids)
        C = 5
        T = self.seq_len
        L = self.depth_levels

        out_tensor = np.zeros((N, C, T, L), dtype=np.float32)
        valid_mask = np.zeros((N,), dtype=bool)

        if orderbook_df is None or snapshots_df is None or N == 0:
            return torch.tensor(out_tensor), torch.tensor(valid_mask)

        ob_win = orderbook_df[orderbook_df["market_id"].isin(market_ids)]
        snap_win = snapshots_df[snapshots_df["market_id"].isin(market_ids)]
        if t_end is not None:
            ts_end = pd.to_datetime(t_end)
            ob_win = ob_win[ob_win["timestamp_received"] <= ts_end]
            snap_win = snap_win[snap_win["timestamp_received"] <= ts_end]

        if ob_win.empty or snap_win.empty:
            return torch.tensor(out_tensor), torch.tensor(valid_mask)

        # Pre-group by market_id for fast lookup
        snap_grouped = snap_win.sort_values("timestamp_received").groupby("market_id", observed=True)
        ob_grouped = ob_win.sort_values("timestamp_received").groupby("market_id", observed=True)

        for idx, m_id in enumerate(market_ids):
            if m_id not in snap_grouped.groups or m_id not in ob_grouped.groups:
                continue

            m_snaps = snap_grouped.get_group(m_id)
            if m_snaps.empty:
                continue

            # Anchor on the latest snapshot that occurred before available ticks, or latest overall
            anchor = m_snaps.iloc[-1]
            t_anchor = anchor["timestamp_received"]
            raw_json = anchor.get("data")
            if not raw_json:
                continue

            try:
                parsed = json.loads(raw_json) if isinstance(raw_json, str) else raw_json
                bids_dict = {float(k): float(v) for k, v in parsed.get("bids", [])}
                asks_dict = {float(k): float(v) for k, v in parsed.get("asks", [])}
            except Exception:
                continue

            # Grab up to `seq_len` tick events occurring AFTER anchor snapshot
            m_ob = ob_grouped.get_group(m_id)
            post_ticks = m_ob[m_ob["timestamp_received"] >= t_anchor].head(self.seq_len)

            if len(post_ticks) == 0:
                continue

            valid_mask[idx] = True

            # Replay tick updates step-by-step
            for step, (_, row) in enumerate(post_ticks.iterrows()):
                # 1. Update resting book state with the tick event delta
                side = str(row.get("change_side", "")).upper()
                p_change = row.get("change_price")
                v_change = row.get("change_size", 0.0)

                if pd.notnull(p_change):
                    p_val = float(p_change)
                    if side == "BUY":
                        bids_dict[p_val] = max(0.0, bids_dict.get(p_val, 0.0) + float(v_change))
                        if bids_dict[p_val] <= 1e-6:
                            bids_dict.pop(p_val, None)
                    elif side == "SELL":
                        asks_dict[p_val] = max(0.0, asks_dict.get(p_val, 0.0) + float(v_change))
                        if asks_dict[p_val] <= 1e-6:
                            asks_dict.pop(p_val, None)

                # 2. Extract top L levels
                sorted_bids = sorted(bids_dict.items(), key=lambda x: x[0], reverse=True)[:L]
                sorted_asks = sorted(asks_dict.items(), key=lambda x: x[0], reverse=False)[:L]

                mid_price = row.get("mid_price")
                if pd.isnull(mid_price) or mid_price == 0:
                    bb = sorted_bids[0][0] if sorted_bids else 0.49
                    ba = sorted_asks[0][0] if sorted_asks else 0.51
                    mid_price = (bb + ba) / 2.0

                # 3. Calculate temporal intensity (elapsed seconds since anchor snapshot)
                dt_sec = max(0.0, (row["timestamp_received"] - t_anchor).total_seconds())
                log_dt = np.log1p(dt_sec)

                # 4. Populate spatial channels
                for l_idx, (p, vol) in enumerate(sorted_bids):
                    out_tensor[idx, 0, step, l_idx] = max(0.0, mid_price - p)  # Bid distance to mid
                    out_tensor[idx, 1, step, l_idx] = vol                      # Bid standing volume
                for l_idx, (p, vol) in enumerate(sorted_asks):
                    out_tensor[idx, 2, step, l_idx] = max(0.0, p - mid_price)  # Ask distance to mid
                    out_tensor[idx, 3, step, l_idx] = vol                      # Ask standing volume

                # Channel 4: Temporal intensity broadcast across levels
                out_tensor[idx, 4, step, :] = float(log_dt)

            # If fewer than seq_len events existed, pad remaining temporal steps with last observed state
            actual_len = len(post_ticks)
            if actual_len < T and actual_len > 0:
                for s in range(actual_len, T):
                    out_tensor[idx, :, s, :] = out_tensor[idx, :, actual_len - 1, :]

        return torch.tensor(out_tensor, dtype=torch.float32), torch.tensor(valid_mask, dtype=torch.bool)


class SpatiotemporalCNNEncoder(nn.Module):
    """
    2D Spatiotemporal Convolutional LOB Encoder (DeepLOB Architecture).
    Applies learnable 2D convolution filters across price depth levels and time steps,
    explicitly conditioning on LOB spatial geometries and event arrival velocities.
    """
    def __init__(self, in_channels: int = 5, seq_len: int = 4, depth_levels: int = 10, hidden_channels: int = 32, out_dim: int = 32):
        super().__init__()
        self.seq_len = seq_len
        self.depth_levels = depth_levels
        # 2D Convolution over (seq_len, depth_levels)
        self.conv1 = nn.Conv2d(in_channels, hidden_channels, kernel_size=(3, 3), padding=(1, 1))
        self.bn1 = nn.BatchNorm2d(hidden_channels)
        self.conv2 = nn.Conv2d(hidden_channels, hidden_channels * 2, kernel_size=(3, 3), padding=(1, 1))
        self.bn2 = nn.BatchNorm2d(hidden_channels * 2)
        self.act = nn.SiLU()
        self.pool = nn.AdaptiveAvgPool2d((1, 1))
        self.fc = nn.Linear(hidden_channels * 2, out_dim)
        self.norm = nn.LayerNorm(out_dim)

    def forward(self, x: torch.Tensor) -> torch.Tensor:
        """
        Args:
            x: Tensor of shape [N_markets, channels=5, seq_len, depth_levels]
        Returns:
            z_cnn: Spatial embedding vector of shape [N_markets, out_dim]
        """
        h = self.act(self.bn1(self.conv1(x)))
        h = self.act(self.bn2(self.conv2(h)))
        h_pooled = self.pool(h).view(x.size(0), -1)
        z_cnn = self.act(self.norm(self.fc(h_pooled)))
        return z_cnn


class HybridLOBEncoder(nn.Module):
    """
    The Ultimate Hybrid LOB Embedding Architecture.
    Simultaneously propagates gradient flow through:
      1. The empirical alpha & velocity network (LOBNeuralEncoder on 12 rich features)
      2. The raw Spatiotemporal LOB convolutional network (SpatiotemporalCNNEncoder on 3D event tensors)
    
    Combines both vectors via a gated fusion layer into a definitive market node LOB embedding.
    """
    def __init__(self, empirical_dim: int = 12, cnn_channels: int = 5, seq_len: int = 4, depth_levels: int = 10, out_dim: int = 32):
        super().__init__()
        self.empirical_encoder = LOBNeuralEncoder(in_dim=empirical_dim, out_dim=out_dim)
        self.cnn_encoder = SpatiotemporalCNNEncoder(
            in_channels=cnn_channels, 
            seq_len=seq_len, 
            depth_levels=depth_levels, 
            out_dim=out_dim
        )
        
        # Gated fusion of empirical summary representation and spatial CNN representation
        self.fusion_gate = nn.Sequential(
            nn.Linear(out_dim * 2, out_dim),
            nn.Sigmoid()
        )
        self.proj = nn.Sequential(
            nn.Linear(out_dim * 2, out_dim),
            nn.LayerNorm(out_dim),
            nn.SiLU()
        )

    def forward(self, emp_feats: torch.Tensor, spatial_tensor: torch.Tensor) -> torch.Tensor:
        """
        Args:
            emp_feats: FloatTensor of shape [N, 12] from LOBFeatureExtractor
            spatial_tensor: FloatTensor of shape [N, 5, seq_len, depth_levels] from SpatiotemporalLOBExtractor
        Returns:
            z_hybrid: Unified LOB embedding vector of shape [N, out_dim]
        """
        z_emp = self.empirical_encoder(emp_feats)
        z_spatial = self.cnn_encoder(spatial_tensor)
        
        combined = torch.cat([z_emp, z_spatial], dim=-1)
        gate_weights = self.fusion_gate(combined)
        
        z_fused = self.proj(combined) * gate_weights
        return z_fused


# ─────────────────────────────────────────────────────────────────────────────
# Continuous-Time Message Generator (Parallel & Pre-Computed Architecture)
# ─────────────────────────────────────────────────────────────────────────────

def _process_single_market_stream(args: Tuple[str, pd.DataFrame, Optional[Tuple[pd.Timestamp, str]], pd.Timestamp, int, int, int, float]) -> Tuple[str, pd.Timestamp, List[Tuple[pd.Timestamp, torch.Tensor, torch.Tensor]], Optional[Tuple[pd.Timestamp, str]]]:
    """
    Independent worker function to process a single market's stream in a separate thread/process.
    """
    m_id, m_events, anchor_state_tuple, checkpoint, min_events, k_slices, depth_levels, depth_price_band = args
    
    market_messages = []
    new_checkpoint = checkpoint
    new_anchor_tuple = None
    
    # 1. Anchor on the newest snapshot <= checkpoint
    if anchor_state_tuple is None:
        # BACKWARD RECONSTRUCTION FOR ORPHANED TICKS!
        # Find the very first true snapshot anywhere in the stream
        m_snaps = m_events[m_events["event_type"] == "snap"]
        if m_snaps.empty:
            # If there's literally no snapshot available, we cannot reconstruct backwards yet.
            return m_id, new_checkpoint, market_messages, new_anchor_tuple
            
        first_real_snap = m_snaps.iloc[0]
        raw_json = first_real_snap.get("data")
        bids_dict = {}
        asks_dict = {}
        if raw_json:
            try:
                parsed = json.loads(raw_json) if isinstance(raw_json, str) else raw_json
                bids_dict = {float(k): float(v) for k, v in parsed.get("bids", [])}
                asks_dict = {float(k): float(v) for k, v in parsed.get("asks", [])}
            except Exception:
                pass
                
        # Traverse backward chronologically from the snapshot to the very first orphaned tick
        orphaned_ticks = m_events[(m_events["event_type"] == "tick") & (m_events["timestamp_received"] <= first_real_snap["timestamp_received"])]
        
        # Traverse backwards! Volume_Before = Volume_After - Delta
        for _, row in orphaned_ticks.sort_values("timestamp_received", ascending=False).iterrows():
            tside = str(row.get("change_side", "")).upper()
            tp = row.get("change_price")
            tdelta = row.get("delta", 0.0) # Pre-computed offline!
            
            if pd.notnull(tp) and not pd.isnull(tdelta):
                p_val = float(tp)
                d_val = float(tdelta)
                if tside == "BUY":
                    bids_dict[p_val] = max(0.0, bids_dict.get(p_val, 0.0) - d_val)
                    if bids_dict[p_val] <= 1e-6: bids_dict.pop(p_val, None)
                elif tside == "SELL":
                    asks_dict[p_val] = max(0.0, asks_dict.get(p_val, 0.0) - d_val)
                    if asks_dict[p_val] <= 1e-6: asks_dict.pop(p_val, None)
                    
        # We have now mathematically deduced the true state of the orderbook at T=0!
        t_start = m_events.iloc[0]["timestamp_received"]
        anchor_timestamp = t_start - pd.Timedelta(milliseconds=1)
        anchor_json = json.dumps({"bids": list(bids_dict.items()), "asks": list(asks_dict.items())})
    else:
        anchor_timestamp, anchor_json = anchor_state_tuple
        
    pending_events = m_events[m_events["timestamp_received"] > checkpoint]
    
    # THE WHILE LOOP: Chunk by min_events
    while len(pending_events) >= min_events:
        chunk = pending_events.iloc[:min_events]
        t_end = chunk.iloc[-1]["timestamp_received"]
        
        # We need all events from anchor_snap up to t_end to replay accurately for the CNN
        replay_stream = m_events[(m_events["timestamp_received"] > anchor_timestamp) & (m_events["timestamp_received"] <= t_end)]
        
        # Reconstruct baseline book for CNN spatial capture
        bids_dict = {}
        asks_dict = {}
        if anchor_json:
            try:
                parsed = json.loads(anchor_json) if isinstance(anchor_json, str) else anchor_json
                bids_dict = {float(k): float(v) for k, v in parsed.get("bids", [])}
                asks_dict = {float(k): float(v) for k, v in parsed.get("asks", [])}
            except Exception:
                pass
        
        # --- A. Setup temporal slices for CNN ---
        t_start_ts = checkpoint.timestamp()
        t_end_ts = t_end.timestamp()
        dt_total = t_end_ts - t_start_ts
        slice_targets = [t_start_ts + dt_total * (i + 1) / k_slices for i in range(k_slices)]
        current_slice_idx = 0
        
        emp_tensor = np.zeros((1, 12), dtype=np.float32)
        spatial_tensor = np.zeros((1, 5, k_slices, depth_levels), dtype=np.float32)
        
        # Instantly aggregate empirical features using the pre-computed DELTA column!
        tick_chunk = chunk[chunk["event_type"] == "tick"]
        tick_count = len(tick_chunk)
        
        total_ofi = 0.0
        total_vol_delta = 0.0
        buy_events = 0
        depletion_events = 0
        
        if tick_count > 0:
            is_buy = (tick_chunk["change_side"].str.upper() == "BUY").astype(int)
            buy_events = is_buy.sum()
            
            # Using the pre-computed delta column (or change_size if missing)
            deltas = tick_chunk.get("delta", tick_chunk["change_size"]).fillna(0.0)
            depletion_events = (deltas < 0).sum()
            total_vol_delta = deltas.abs().sum()
            
            # OFI: (+1 for buy, -1 for sell) * delta
            signs = np.where(is_buy == 1, 1.0, -1.0)
            total_ofi = (signs * deltas).sum()
            
        mid_val = 0.50
        
        # --- B. Replay Stream (Only for CNN Spatial Tensor) ---
        cols = ["timestamp_received", "event_type", "data", "change_side", "change_price", "change_size", "mid_price"]
        for row in replay_stream[cols].itertuples(index=False, name=None):
            row_ts = row[0].timestamp()
            
            # Capture spatial state for any slices we've passed
            while current_slice_idx < k_slices and row_ts > slice_targets[current_slice_idx]:
                sb = sorted(bids_dict.items(), key=lambda x: x[0], reverse=True)[:depth_levels]
                sa = sorted(asks_dict.items(), key=lambda x: x[0], reverse=False)[:depth_levels]
                elapsed_log = np.log1p(max(0.0, slice_targets[current_slice_idx] - anchor_timestamp.timestamp()))
                
                for l_idx, (p, vol) in enumerate(sb):
                    spatial_tensor[0, 0, current_slice_idx, l_idx] = max(0.0, mid_val - p)
                    spatial_tensor[0, 1, current_slice_idx, l_idx] = vol
                for l_idx, (p, vol) in enumerate(sa):
                    spatial_tensor[0, 2, current_slice_idx, l_idx] = max(0.0, p - mid_val)
                    spatial_tensor[0, 3, current_slice_idx, l_idx] = vol
                spatial_tensor[0, 4, current_slice_idx, :] = float(elapsed_log)
                current_slice_idx += 1
                
            # Update dictionary (Required purely for CNN state capture)
            event_type = row[1]
            if event_type == "snap":
                r_json = row[2]
                if pd.notnull(r_json):
                    try:
                        parsed = json.loads(r_json) if isinstance(r_json, str) else r_json
                        bids_dict = {float(k): float(v) for k, v in parsed.get("bids", [])}
                        asks_dict = {float(k): float(v) for k, v in parsed.get("asks", [])}
                    except Exception:
                        pass
            elif event_type == "tick":
                tside = str(row[3]).upper()
                tp = row[4]
                tv = row[5]
                mid_m = row[6]
                
                if pd.notnull(mid_m) and mid_m != 0:
                    mid_val = float(mid_m)

                if pd.notnull(tp):
                    p_val = float(tp)
                    v_val = float(tv) if pd.notnull(tv) else 0.0
                    if tside == "BUY":
                        if v_val <= 1e-6: bids_dict.pop(p_val, None)
                        else: bids_dict[p_val] = v_val
                    elif tside == "SELL":
                        if v_val <= 1e-6: asks_dict.pop(p_val, None)
                        else: asks_dict[p_val] = v_val
                        
        # Fill any remaining temporal slices with the final state at t_end
        while current_slice_idx < k_slices:
            sb = sorted(bids_dict.items(), key=lambda x: x[0], reverse=True)[:depth_levels]
            sa = sorted(asks_dict.items(), key=lambda x: x[0], reverse=False)[:depth_levels]
            elapsed_log = np.log1p(max(0.0, slice_targets[current_slice_idx] - anchor_timestamp.timestamp()))
            for l_idx, (p, vol) in enumerate(sb):
                spatial_tensor[0, 0, current_slice_idx, l_idx] = max(0.0, mid_val - p)
                spatial_tensor[0, 1, current_slice_idx, l_idx] = vol
            for l_idx, (p, vol) in enumerate(sa):
                spatial_tensor[0, 2, current_slice_idx, l_idx] = max(0.0, p - mid_val)
                spatial_tensor[0, 3, current_slice_idx, l_idx] = vol
            spatial_tensor[0, 4, current_slice_idx, :] = float(elapsed_log)
            current_slice_idx += 1
            
        # --- C. Finalize Empirical Features ---
        emp_tensor[0, 0] = mid_val
        
        sb = sorted(bids_dict.items(), key=lambda x: x[0], reverse=True)
        sa = sorted(asks_dict.items(), key=lambda x: x[0], reverse=False)
        bb = sb[0][0] if sb else 0.49
        ba = sa[0][0] if sa else 0.51
        emp_tensor[0, 1] = max(0.0, ba - bb)
        emp_tensor[0, 2] = bb
        emp_tensor[0, 3] = ba
        
        # Pre-computed sums
        emp_tensor[0, 4] = float(total_ofi)
        emp_tensor[0, 5] = float(total_vol_delta)
        emp_tensor[0, 6] = float(tick_count)
        emp_tensor[0, 7] = float(buy_events) / (tick_count + 1e-5)
        emp_tensor[0, 8] = float(depletion_events) / (tick_count + 1e-5)
        
        bvols = [v for p, v in bids_dict.items() if (mid_val - p) <= depth_price_band]
        avols = [v for p, v in asks_dict.items() if (p - mid_val) <= depth_price_band]
        mb = np.mean(bvols) if len(bvols) > 0 else 0.0
        ma = np.mean(avols) if len(avols) > 0 else 0.0
        emp_tensor[0, 9] = float(mb)
        emp_tensor[0, 10] = float(ma)
        emp_tensor[0, 11] = float((mb - ma) / (mb + ma + 1e-5))
        
        # Pack message
        # Convert to numpy to avoid PyTorch IPC file descriptor exhaustion ("Too many open files")
        market_messages.append((t_end, emp_tensor.astype(np.float32), spatial_tensor.astype(np.float32)))
        
        # Advance Checkpoint and shrink pending queue
        new_checkpoint = t_end
        pending_events = pending_events.iloc[min_events:]
        new_anchor_json = json.dumps({"bids": list(bids_dict.items()), "asks": list(asks_dict.items())})
        anchor_timestamp = new_checkpoint
        anchor_json = new_anchor_json
        new_anchor_tuple = (anchor_timestamp, anchor_json)
        
    return m_id, new_checkpoint, market_messages, new_anchor_tuple


class ContinuousLOBMessageEngine:
    """
    Massively Parallel Continuous-Time LOB Message Generator.
    
    Utilizes multiprocessing to process every market independently and simultaneously.
    Leverages the pre-computed `delta` column in the Parquet files to calculate Order Flow Imbalance
    and Volume Depletion metrics instantly via vectorized operations, bypassing the dictionary overhead.
    """
    def __init__(self, min_events: int = 20, k_slices: int = 4, depth_levels: int = 10, depth_price_band: float = 0.05, num_workers: int = 4):
        self.min_events = min_events
        self.k_slices = k_slices
        self.depth_levels = depth_levels
        self.depth_price_band = depth_price_band
        self.num_workers = num_workers
        self.checkpoints: Dict[str, pd.Timestamp] = {}
        # We store the latest anchor state tuple (timestamp, json) for each market across step() calls
        self.anchor_states: Dict[str, Tuple[pd.Timestamp, str]] = {}

    def reset(self):
        """Clear cursor history."""
        self.checkpoints.clear()
        self.anchor_states.clear()

    def step(
        self,
        market_ids: List[str],
        orderbook_df: pd.DataFrame,
        snapshots_df: pd.DataFrame,
        t_query: pd.Timestamp | str,
    ) -> Dict[str, List[Tuple[pd.Timestamp, torch.Tensor, torch.Tensor]]]:
        """
        Generates a sequence of LOB message tensors for active markets in parallel.
        """
        import multiprocessing
        import time
        t_start_prep = time.time()
        
        t_query = pd.to_datetime(t_query)
        results = {}

        if orderbook_df is None or snapshots_df is None or len(market_ids) == 0:
            return results

        # Pre-filter dataset up to t_query
        ob_win = orderbook_df[(orderbook_df["market_id"].isin(market_ids)) & (orderbook_df["timestamp_received"] <= t_query)].copy()
        snap_win = snapshots_df[(snapshots_df["market_id"].isin(market_ids)) & (snapshots_df["timestamp_received"] <= t_query)].copy()

        if ob_win.empty and snap_win.empty:
            return results

        ob_win["event_type"] = "tick"
        snap_win["event_type"] = "snap"
        
        all_events = pd.concat([snap_win, ob_win]).sort_values("timestamp_received")
        grouped_events = all_events.groupby("market_id", observed=True)

        # Prepare arguments for the process pool
        pool_args = []
        for m_id in market_ids:
            if m_id not in grouped_events.groups:
                continue

            m_events = grouped_events.get_group(m_id)
            checkpoint = self.checkpoints.get(m_id, None)

            # Handle Beginning of Time
            if checkpoint is None:
                # We anchor on the VERY FIRST event ever received for this market!
                checkpoint = m_events.iloc[0]["timestamp_received"]
                self.checkpoints[m_id] = checkpoint

            # Create the anchor state tuple to pass to the worker
            anchor_state_tuple = self.anchor_states.get(m_id, None)

            pool_args.append((
                m_id, 
                m_events, 
                anchor_state_tuple, 
                checkpoint, 
                self.min_events, 
                self.k_slices, 
                self.depth_levels, 
                self.depth_price_band
            ))

        if not pool_args:
            return results

        t_end_prep = time.time()

        # Execute processing massively in parallel
        t_start_workers = time.time()
        with multiprocessing.Pool(processes=self.num_workers) as pool:
            worker_results = pool.map(_process_single_market_stream, pool_args)
        t_end_workers = time.time()

        # Re-integrate the updated state and results from the workers
        t_start_reintegrate = time.time()
        for m_id, new_checkpoint, market_messages, new_anchor_tuple in worker_results:
            if market_messages:
                results[m_id] = market_messages
                self.checkpoints[m_id] = new_checkpoint
                if new_anchor_tuple is not None:
                    self.anchor_states[m_id] = new_anchor_tuple
        t_end_reintegrate = time.time()
        
        print(f"      [Engine Timing] Pre-filter & Grouping: {t_end_prep - t_start_prep:.3f}s")
        print(f"      [Engine Timing] Worker Pool Execution: {t_end_workers - t_start_workers:.3f}s")
        print(f"      [Engine Timing] Reintegration:         {t_end_reintegrate - t_start_reintegrate:.3f}s")

        return results


